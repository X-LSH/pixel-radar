/** 字形位掩码缓存：glyph -> Uint8Array(ROWS)，每位代表一列 */
const maskCache = new Map();

function parseGlyph(def) {
  const rows = def.split('/');
  const mask = new Uint8Array(ROWS);
  for (let r = 0; r < ROWS; r++) {
    const line = rows[r] || '';
    let bits = 0;
    for (let c = 0; c < COLS; c++) if (line.charCodeAt(c) === 49) bits |= 1 << (COLS - 1 - c);
    mask[r] = bits;
  }
  return mask;
}

function lookup(ch) {
  let m = maskCache.get(ch);
  if (m) return m;
  if (Object.prototype.hasOwnProperty.call(EXTRA, ch)) {
    m = parseGlyph(EXTRA[ch]);
  } else {
    const code = ch.charCodeAt(0);
    // 屏内一律大写：小写折叠
    const up = code >= 97 && code <= 122 ? code - 32 : code;
    if (up >= 0x20 && up < 0x20 + ASCII.length) m = parseGlyph(ASCII[up - 0x20]);
    else m = parseGlyph(ASCII[0]);
  }
  maskCache.set(ch, m);
  return m;
}

/** 字距：字宽 5 + 间隔 1 = 6 逻辑像素 */
export const ADVANCE = COLS + 1;
export const GLYPH_W = COLS;
export const GLYPH_H = ROWS;

export function measure(text) {
  const n = text.length;
  return n === 0 ? 0 : n * ADVANCE - 1;
}

/**
 * 绘制位图文字。
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x 左基线（整数）
 * @param {number} y 顶边（整数）
 * @param {string} color
 * @param {{shadow?:string, alpha?:number, spacing?:number}} [opts]
 */
export function drawText(ctx, text, x, y, color, opts = {}) {
  const shadow = opts.shadow;
  const alpha = opts.alpha == null ? 1 : opts.alpha;
  const adv = ADVANCE + (opts.spacing || 0);
  const prevAlpha = ctx.globalAlpha;

  if (alpha !== 1) ctx.globalAlpha = prevAlpha * alpha;

  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === ' ') continue;
    const mask = lookup(ch);
    const gx = (x + i * adv) | 0;
    const gy = y | 0;

    if (shadow) {
      ctx.fillStyle = shadow;
      for (let r = 0; r < ROWS; r++) {
        const bits = mask[r];
        if (!bits) continue;
        for (let c = 0; c < COLS; c++) {
          if (bits & (1 << (COLS - 1 - c))) ctx.fillRect(gx + c + 1, gy + r + 1, 1, 1);
        }
      }
    }

    ctx.fillStyle = color;
    for (let r = 0; r < ROWS; r++) {
      const bits = mask[r];
      if (!bits) continue;
      // 同行连续点合并成一次 fillRect，减少调用次数
      let runStart = -1;
      for (let c = 0; c <= COLS; c++) {
        const on = c < COLS && bits & (1 << (COLS - 1 - c));
        if (on && runStart < 0) runStart = c;
        else if (!on && runStart >= 0) {
          ctx.fillRect(gx + runStart, gy + r, c - runStart, 1);
          runStart = -1;
        }
      }
    }
  }

  if (alpha !== 1) ctx.globalAlpha = prevAlpha;
}

/** 右对齐绘制 */
export function drawTextRight(ctx, text, rightX, y, color, opts) {
  drawText(ctx, text, rightX - measure(text), y, color, opts);
}

/** 居中绘制 */
export function drawTextCenter(ctx, text, cx, y, color, opts) {
  drawText(ctx, text, cx - measure(text) / 2, y, color, opts);
}

/** 供自检脚本遍历字形使用 */
export function fontStats() {
  return { ascii: ASCII.length, extra: Object.keys(EXTRA).length, rows: ROWS, cols: COLS };
}
