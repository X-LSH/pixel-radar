/**
 * Pixel Radar · 5×7 位图字体
 * ---------------------------------------------------------------
 * 为什么不用 ctx.fillText：
 *   1. 浏览器字体在 5~8px 下会被抗锯齿糊成一团，与像素美学冲突；
 *   2. 屏内文字必须与「整数倍放大」严格对齐，不能有半像素；
 *   3. 我们需要完全掌控字形（雷达屏只认大写 + 数字 + 少量符号）。
 *
 * 字形以「ASCII 点阵」书写而非 hex —— 因为十六进制没法用肉眼校验，
 * 点阵写错了当场就能看出来。字形按行从上到下，1 = 点亮。
 *
 * 屏幕内一律使用大写；drawText 会自动把 <128 的小写转成大写。
 * 中文不进屏内 —— 屏内是 CRT 字符发生器，中文走 DOM 外壳。
 */

